"""The commit and PR policy enforced in CI and by the commit-msg hook."""

import importlib.util
from pathlib import Path

import pytest

_spec = importlib.util.spec_from_file_location(
    "check_commit_policy", Path(__file__).resolve().parent.parent / "scripts" / "ci" / "check_commit_policy.py"
)
policy = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(policy)


@pytest.mark.parametrize(
    "subject",
    [
        "feat(practice): add stock picker (T03)",
        "fix: handle empty feed",
        "content(learn): add volume lesson",
        "ci!: require coverage",
    ],
)
def test_good_subjects_pass(subject):
    assert policy.check_subject(subject, "x") == []


@pytest.mark.parametrize(
    "subject", ["Added stuff", "feat:missing space", "Feature(practice): picker", "feat(Practice): caps scope"]
)
def test_bad_subjects_fail(subject):
    assert policy.check_subject(subject, "x")


@pytest.mark.parametrize(
    "body",
    [
        "Co-Authored-By: Claude Opus <noreply@anthropic.com>",
        "co-authored-by: GitHub Copilot <x@y>",
        "🤖 Generated with Claude Code",
        "Generated by ChatGPT",
    ],
)
def test_ai_attribution_is_rejected(body):
    assert policy.check_message(f"feat: add picker\n\n{body}", "x")


def test_human_co_author_is_allowed():
    assert policy.check_message("feat: add picker\n\nCo-Authored-By: Devansh <d@example.com>", "x") == []
